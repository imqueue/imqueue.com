#!/usr/bin/env node
// gen-api-crosslinks.js — emit lib/api-crosslinks.js.
//
// @imqueue/rpc re-exports the whole @imqueue/core surface, so up to and
// including rpc 3.2.1 the generated reference documented every core symbol twice
// — once under /api/core/latest/core.<sym>/ and again under
// /api/rpc/latest/rpc.<sym>/. build-api-docs.js now strips those re-exports
// before running API Extractor (see stripReexports: core has its own pages, and
// bundling trips an api-extractor defect), which is the right call for the docs.
//
// The side effect was never handled: ~159 rpc URLs that Google had already
// indexed started returning a hard 404 instead of pointing at the core page that
// replaced them. This emits the salvage map, which the Pages Functions use to
// 301 them onto the canonical core page.
//
// Derived from what is on disk, so it cannot claim a mapping for a page that
// does not exist. Run standalone or via `npm run build-docs`.
//
//   node scripts/gen-api-crosslinks.js

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const API_DIR = path.join(ROOT, 'src', 'org', 'api');

// Symbol basenames documented in <pkg>/latest, with the "<pkg>." prefix removed.
function symbolsOf(pkg) {
  const dir = path.join(API_DIR, pkg, 'latest');

  if (!fs.existsSync(dir)) {
    return new Set();
  }

  return new Set(
    fs.readdirSync(dir)
      .filter(f => f.endsWith('.md') && f !== 'index.md')
      .map(f => f.replace(/\.md$/, ''))
      .filter(b => b.startsWith(`${pkg}.`))
      .map(b => b.slice(pkg.length + 1)),
  );
}

function generate() {
  const core = symbolsOf('core');
  const rpc = symbolsOf('rpc');

  // A core symbol rpc no longer documents itself: the re-export that went away.
  const orphaned = [...core].filter(s => !rpc.has(s)).sort();

  const file = path.join(ROOT, 'lib', 'api-crosslinks.js');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `// GENERATED by scripts/gen-api-crosslinks.js — do not edit by hand.
//
// @imqueue/core symbols that @imqueue/rpc used to re-export (and therefore used
// to document at /api/rpc/latest/rpc.<symbol>/) but no longer does. Those URLs
// were indexed, so they 301 onto the core page instead of 404ing.
export const CORE_REEXPORTS = new Set(${JSON.stringify(orphaned, null, 2).replace(/\n/g, '\n  ')});
`);

  console.log(
    `Wrote lib/api-crosslinks.js — ${orphaned.length} core symbols no longer ` +
    `documented under rpc (core: ${core.size}, rpc: ${rpc.size})`,
  );

  return orphaned;
}

if (require.main === module) {
  generate();
}

module.exports = { generate };
